export function parseScore(doc) {
    const part = doc.getElementsByTagName("score-partwise")[0];
    const measures = part.getElementsByTagName("measure");

    let bpm = 60;
    let beatUnit = "quarter";
    let metronomeMarkIsDotted = false;
    let beatsPerMeasure = 4;
    let timeSignatureDenominator = 4;

    this.musicxmlScore = {
        measures: {},
        useAIModel: false,
    };

    let divisionsFactor = 1;
    let isTremolo = false;
    let tremoloType = null;
    let isTied = false;
    let tiedType = null;

    // Credits (title/composer)
    const credits = part.getElementsByTagName("credit");
    for (let credit of credits) {
        const creditType = credit.getElementsByTagName("credit-type")[0];
        if (!creditType) continue;
        const text = creditType.textContent;
        const creditWords = credit.getElementsByTagName("credit-words");
        if (text === "title" && creditWords.length > 0) {
            this.musicxmlScore.pieceName = creditWords[0].textContent;
        }
        if (text === "composer" && creditWords.length > 0) {
            this.musicxmlScore.pieceComposer = creditWords[0].textContent;
        }
    }

    var measureNumber = 0;
    for (let measure of measures) {
        measureNumber++;
        const attributes = measure.getElementsByTagName("attributes")[0];
        if (attributes) {
            const divisions = attributes.getElementsByTagName("divisions")[0];
            if (divisions) {
                divisionsFactor = parseInt(divisions.textContent, 10);
            }
            const time = attributes.getElementsByTagName("time")[0];
            if (time) {
                const beats = time.getElementsByTagName("beats")[0];
                const beatType = time.getElementsByTagName("beat-type")[0];

                if (beats) beatsPerMeasure = parseInt(beats.textContent, 10);
                if (beatType) timeSignatureDenominator = parseInt(beatType.textContent, 10);
            }
        }

        const metronome = measure.getElementsByTagName("metronome")[0];
        if (metronome) {
            const beatUnitEl = metronome.getElementsByTagName("beat-unit")[0];
            const bpmEl = metronome.getElementsByTagName("per-minute")[0];
            const dot = metronome.getElementsByTagName("beat-unit-dot").length > 0;
            if (beatUnitEl) beatUnit = beatUnitEl.textContent;
            if (bpmEl) bpm = parseFloat(bpmEl.textContent);
            metronomeMarkIsDotted = dot;
        }

        const notes = measure.getElementsByTagName("note");
        const measureNotes = [];

        for (let i = 0; i < notes.length; i++) {
            const note = notes[i];
            const chord = note.getElementsByTagName("chord").length > 0;
            const pitch = note.getElementsByTagName("pitch")[0];
            const tremolo = note.getElementsByTagName("tremolo");
            const tied = note.getElementsByTagName("tied");
            const notehead = note.getElementsByTagName("notehead");

            // tremolo state
            if (tremolo.length > 0) {
                isTremolo = true;
                tremoloType = tremolo[0].getAttribute("type");
            } else {
                isTremolo = false;
                tremoloType = null;
            }

            // tied state
            if (tied.length > 0) {
                isTied = true;
                tiedType = tied[0].getAttribute("type");
            } else {
                isTied = false;
                tiedType = null;
            }
            // pitch extraction
            let step = null;
            let octave = null;
            let alter = null;

            if (pitch) {
                const stepEl = pitch.getElementsByTagName("step")[0];
                const octaveEl = pitch.getElementsByTagName("octave")[0];
                const alterEl = pitch.getElementsByTagName("alter")[0];
                if (stepEl) step = stepEl.textContent;
                if (octaveEl) octave = parseInt(octaveEl.textContent, 10);
                if (alterEl) alter = parseInt(alterEl.textContent, 10);
            }

            const durationEl = note.getElementsByTagName("duration")[0];
            const rawDuration = durationEl ? parseFloat(durationEl.textContent) : 0;
            const duration = rawDuration / (timeSignatureDenominator / divisionsFactor);
            const rest = note.getElementsByTagName("rest")[0];
            const noteheadString = notehead.length > 0 ? notehead[0].textContent : "";
            const isExtendedTechnique = notehead.length > 0;

            if (notehead.length > 0) {
                this.musicxmlScore.useAIModel = true;
            }

            let beatValueMultiplier = 1;

            if (beatUnit === "whole") beatValueMultiplier = 1;
            if (beatUnit === "half") beatValueMultiplier = 2;
            if (beatUnit === "quarter") beatValueMultiplier = 4;
            if (beatUnit === "eighth") beatValueMultiplier = 8;
            if (beatUnit === "16th") beatValueMultiplier = 16;
            if (beatUnit === "32nd") beatValueMultiplier = 32;

            if (metronomeMarkIsDotted) {
                beatValueMultiplier /= 1.5;
            }

            // console.log(timeSignatureDenominator, beatValueMultiplier);
            const normalizedBpm = bpm * (timeSignatureDenominator / beatValueMultiplier);

            const noteObj = {
                bpm: normalizedBpm,
                timeUnit: beatUnit,
                metronomeMarkDotted: metronomeMarkIsDotted,
                beatsPerMeasure,
                timeSignatureDenominator,
                step,
                octave,
                alter,
                duration,
                isRest: !!rest,
                isTremolo,
                tremoloType,
                isTied,
                tiedType,
                measureNumber,
                isChord: chord,
                isExtendedTechnique,
                notehead: noteheadString,
            };

            measureNotes.push(noteObj);
        }
        this.musicxmlScore.measures[measureNumber] = measureNotes;
    }

    this.generateOpenScofoScore();
    this.handleCodeChange();
}

