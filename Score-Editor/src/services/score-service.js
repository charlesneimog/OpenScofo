export function generateOpenScofoScore() {
    let score = "";
    score += `/* Generated by OpenScofo online editor`;
    if (this.musicxmlScore.pieceName && this.musicxmlScore.pieceComposer) {
        score += `\n${this.musicxmlScore.pieceName} by ${this.musicxmlScore.pieceComposer}\n`;
        score += `*/\n\n`;
    } else {
        score += ` */\n\n`;
    }

    const measures = this.musicxmlScore.measures;
    const allNotes = [];
    for (const measureNumber in measures) {
        const measure = measures[measureNumber];
        for (const note of measure) {
            allNotes.push(note);
        }
    }

    let bpm = allNotes.length > 0 ? allNotes[0].bpm : 60;
    score += `BPM ${bpm}\n\n`;
    let i = 0;
    let lastMeasureNumber = null;

    if (this.musicxmlScore.useAIModel) {
        score += `// Your seems to be using extended techniques, this required one AI model\n`;
        score += `ONNXMODEL PUT-YOUR-MODEL-NAME-HERE.onnx\n`;
        score += `ONNXDESCRIPTORS mfcc logmel centroid flatness hfr flux zcr irregularity kurtosis`;
    }

    while (i < allNotes.length) {
        const note = allNotes[i];
        if (!note) {
            i++;
            continue;
        }

        // measure boundary
        if (note.measureNumber !== lastMeasureNumber) {
            score += `\n\n// Measure number ${note.measureNumber}`;
            lastMeasureNumber = note.measureNumber;
        }

        // BPM change
        if (note.bpm !== bpm) {
            bpm = note.bpm;
            score += `\nBPM ${bpm}\n`;
        }

        // REST
        if (note.isRest) {
            score += `\nREST ${note.duration}`;
            i++;
            continue;
        }

        // INITIAL STATE
        let duration = note.duration;
        let pitches = [this.getPitch(note)];
        let type = "NOTE";

        let j = i + 1;

        // TIES (safe chain)
        if (note.isTied) {
            while (j < allNotes.length && allNotes[j]?.isTied) {
                const n = allNotes[j];
                duration += n.duration;
                j++;
            }
        }

        // CHORD GROUPING (safe)
        if (note.isChord) {
            type = "CHORD";
            while (j < allNotes.length && allNotes[j]?.isChord) {
                pitches.push(this.getPitch(allNotes[j]));
                j++;
            }
        }

        // TREMOLO GROUPING (safe)
        if (note.isTremolo) {
            type = "TRILL";

            while (j < allNotes.length && allNotes[j]?.isTremolo) {
                pitches.push(this.getPitch(allNotes[j]));
                duration += allNotes[j].duration;

                if (allNotes[j].tremoloType === "stop") {
                    j++;
                    break;
                }

                j++;
            }
        }

        // EXTENDED TECHNIQUE
        if (note.isExtendedTechnique) {
            const pitch = this.getPitch(note);
            score += `\nPTECH ${note.notehead} ${pitch} ${duration}`;
            i = j;
            continue;
        }

        // OUTPUT
        if (pitches.length > 1) {
            score += `\n${type} (${pitches.join(" ")}) ${duration}`;
        } else {
            score += `\n${type} ${pitches[0]} ${duration}`;
        }

        if (note.isTied) {
            score += " // tied";
        }

        i = j;
    }

    this.codeEditor.setValue(score);
}

